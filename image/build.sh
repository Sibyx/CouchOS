#!/usr/bin/env bash
# Build the CouchOS base image with pi-gen (arm64 branch) inside Docker.
#
#   image/build.sh              full build
#   CONTINUE=1 image/build.sh   resume after fixing a failed step
#
# pi-gen is a third-party tool. It is cloned into a build cache OUTSIDE this
# repository ($COUCHOS_BUILD_DIR, default ~/.cache/couchos) so it never shows
# up as a nested git repo. The finished image is copied to out/.
# macOS ships bash 3.2: no arrays, no ${var,,}.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$HERE")"
BUILD_DIR="${COUCHOS_BUILD_DIR:-$HOME/.cache/couchos}"
PIGEN="$BUILD_DIR/pi-gen"
PIGEN_REF="${PIGEN_REF:-arm64}"
SSH_KEYS_URL="${SSH_KEYS_URL:-https://github.com/Sibyx.keys}"
OUT="$ROOT/out"

mkdir -p "$BUILD_DIR" "$OUT"
if [ ! -d "$PIGEN/.git" ]; then
	git clone --depth 1 --branch "$PIGEN_REF" https://github.com/RPi-Distro/pi-gen.git "$PIGEN"
fi

# The Docker build COPYs the whole pi-gen tree, so our stage must live inside it.
rm -rf "$PIGEN/stage-couchos"
cp -R "$HERE/stage-couchos" "$PIGEN/stage-couchos"
find "$PIGEN/stage-couchos" -name '*.sh' -exec chmod +x {} +

keys="$(curl -fsSL "$SSH_KEYS_URL")"
if [ -z "$keys" ]; then
	echo "No SSH public keys found at $SSH_KEYS_URL" >&2
	exit 1
fi

GIT_HASH="$(git -C "$PIGEN" rev-parse HEAD)"
export GIT_HASH

cfg="$PIGEN/config"
cp "$HERE/config" "$cfg"
{
	echo
	echo "# --- generated by image/build.sh ---"
	# pi-gen insists on a password when the first-boot rename is disabled.
	# stage-couchos locks it again, so this value is never usable.
	echo "FIRST_USER_PASS='$(openssl rand -hex 24)'"
	printf 'PUBKEY_SSH_FIRST_USER=%q\n' "$keys"
} >>"$cfg"
chmod 600 "$cfg"

# No "-c": build-docker.sh rewrites that path with GNU-only sed (\s), which
# macOS sed ignores. pi-gen/config is picked up (and COPYed) automatically.
cd "$PIGEN"
./build-docker.sh

cp "$PIGEN"/deploy/*couchos*.img.xz "$PIGEN"/deploy/*couchos*.info "$OUT/"
ls -lh "$OUT"
